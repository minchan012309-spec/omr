"""맞춤법 지식 표 1: 소리에 관한 것(제5~12항). 항목 = (옳은 표기, [틀린 표기들], 근거).
틀린 표기는 학생들이 실제로 자주 쓰는 오표기만 넣는다(실재하는 다른 단어가 되는 형태는 넣지 않는다)."""

def _p(block):
    out = []
    for ln in block.strip().splitlines():
        ln = ln.strip()
        if not ln or ln.startswith('#'): continue
        a = [x.strip() for x in ln.split('|')]
        out.append((a[0], [x.strip() for x in a[1].split('/')], a[2] if len(a) > 2 else ''))
    return out

