def mk(s, **meta):
    return Ann(josa(s), **meta)

def hon_sm(r, end='해라', past=None):
    """주체 높임: S께서 pre셨다. (+ 종결 어미 등급 표시)"""
    s = r.choice(SUBJ_H); pre = r.choice(SM_PRE)
    if past is None: past = r.random() < .6
    t = '{셨|SM}' if past else '{신|SM}'
    if end == '해라':
        tail = '{다|HR:해라}' if past else '{다|HR:해라}'
        txt = '%s{께서|SJ} %s%s다.' % (s, pre, t)
        if past:
            txt = '%s{께서|SJ} %s{셨|SM}다.' % (s, pre)
        else:
            txt = '%s{께서|SJ} %s{신|SM}다.' % (s, pre)
    else:
        e = HR_END[end]
        if past:
            txt = '%s{께서|SJ} %s{셨|SM}{%s|HR:%s}.' % (s, pre, e, end)
        else:
            # 현재: 시 + ㅂ니다 → 십니다 등은 활용이 복잡하므로 과거형만 사용
            txt = '%s{께서|SJ} %s{셨|SM}{%s|HR:%s}.' % (s, pre, e, end)
    return mk(txt)

def hon_obj_s(r):
    o = r.choice(OBJ_H)
    kind = r.choice(['drl', 'mos', 'yeo', 'bwe'])
    if kind == 'drl':
        n = r.choice(['선물을', '편지를', '꽃을', '용돈을', '인사를', '과일을', '안부를', '소식을', '책을'])
        return mk('나는 %s{께|OJ} %s {드렸|OL}다.' % (o, n))
    if kind == 'mos':
        p = r.choice(['병원', '시장', '공원', '시골', '학교', '역', '극장'])
        return mk('나는 %s을(를) {모시|OL}고 %s에 갔다.' % (o, p))
    if kind == 'yeo':
        q = r.choice(['길을', '안부를', '궁금한 점을', '시험 범위를', '약속 시간을'])
        return mk('나는 %s{께|OJ} %s {여쭈었|OL}다.' % (o, q))
    return mk('나는 %s을(를) {뵙|OL}고 왔다.' % o)

def hon_hr(r, level=None):
    level = level or r.choice(list(HR_END))
    fr, st, forms = r.choice(HR_V)
    s = r.choice(NORM_S)
    subj = s + ('이' if (ord(s[-1]) - 0xAC00) % 28 else '가')
    return mk('%s %s {%s|HR:%s}.' % (subj, fr, forms[level], level))

def hon_all(r):
    """주체+객체+상대 높임이 함께 쓰인 문장"""
    sh = r.choice(SUBJ_H); o = r.choice([x for x in OBJ_H if x != sh])
    n = r.choice(['선물을', '편지를', '꽃을', '과일을'])
    end = r.choice(['합쇼', '해요'])
    e = HR_END[end]
    return mk('%s{께서|SJ} %s{께|OJ} %s {드리|OL}{셨|SM}{%s|HR:%s}.' % (sh, o, n, e, end))


