def tense_rel(r, code=None):
    code = code or r.choice(['PB', 'RB', 'FB'])
    v = r.choice(RK)
    f_ = {'PB': v[1], 'RB': v[2], 'FB': v[3]}[code]
    tmpl = r.choice(['이것은 내가 {%s|%s} %s이다.', '내가 {%s|%s} %s이(가) 마음에 든다.', '나는 동생이 {%s|%s} %s을(를) 좋아한다.'])
    txt = tmpl % (f_, code, v[4])
    return Ann(josa(txt))

