def tense_s(r, code=None, with_time=True):
    code = code or r.choice(['PA', 'RA', 'FA'])
    fr, pa, ra, fa = r.choice(VT)
    verb = {'PA': pa, 'RA': ra, 'FA': fa}[code]
    s = r.choice(SUBJ_N)
    if with_time:
        tm = r.choice(TIME[code])
        return Ann('{%s|TA} %s %s%s.' % (tm, s, fr, verb))
    return Ann('%s %s%s.' % (s, fr, verb))

