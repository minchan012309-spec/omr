def _facts():
    F = []
    for ph, t, why in CASE_BANK:
        if t in ('주격 조사', '관형격 조사', '목적격 조사', '부사격 조사'):
            F.append(('조사', ph, '밑줄 친 부분에 %s가 쓰였다.' % t, ['밑줄 친 부분에 %s가 쓰였다.' % x for x in ('주격 조사', '관형격 조사', '목적격 조사', '부사격 조사') if x != t], why))
    for old, new, t, d in PHON:
        F.append(('음운', '%s → %s' % (U(old), new), '%s은(는) %s의 예이다.' % (old, t), ['%s은(는) %s의 예이다.' % (old, x) for x in PTYPES if x != t], d))
    for w, a, b, t in SEM:
        F.append(('의미', '%s (%s → %s)' % (U(w), a, b), '%s은(는) %s의 예이다.' % (w, t), ['%s은(는) %s의 예이다.' % (w, x) for x in SEMT if x != t], '%s: %s → %s' % (w, a, b)))
    for m, ex, t in MARK:
        F.append(('높임', '%s (예: %s)' % (U(m), ex), '%s은(는) %s을(를) 나타낸다.' % (m, t), ['%s은(는) %s을(를) 나타낸다.' % (m, x) for x in MK_OPT if x != t], '%s은(는) %s이다.' % (m, t)))
    for ph, t, why in QS:
        F.append(('의문', ph, '밑줄 친 부분은 %s에 쓰였다.' % t, ['밑줄 친 부분은 %s에 쓰였다.' % x for x in QOPT if x != t], why))
    return F
FACTS = _facts()

