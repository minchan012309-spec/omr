    if len(cats) < 5: return None
    pick = r.sample(cats, 5)
    fs = [r.choice([f for f in FACTS if f[0] == c]) for c in pick]
    r.shuffle(fs)
    mode = r.choice(['not', 'ok', 'not'])
    lab = '㉠㉡㉢㉣㉤'
    show = BOX(['%s %s' % (lab[i], f[1]) for i, f in enumerate(fs)], title='자 료')
    bad = r.randrange(5)
    opts, st = [], []
    for i, f in enumerate(fs):
        if (mode == 'not' and i == bad) or (mode == 'ok' and i != bad):
            s = r.choice(f[3]); ok = False
