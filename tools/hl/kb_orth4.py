# 띄어쓰기: (규정 키, 옳은 문장, [틀린 문장들], 설명)
def _sp(block):
    out = []
    for ln in block.strip().splitlines():
        ln = ln.strip()
        if not ln or ln.startswith('#'): continue
        a = [x.strip() for x in ln.split('|')]
        out.append(dict(key=a[0], ok=a[1], bad=[x.strip() for x in a[2].split('/')], why=a[3]))
