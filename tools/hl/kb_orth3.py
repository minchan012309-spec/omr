def _s(block):
    out = []
    for ln in block.strip().splitlines():
        ln = ln.strip()
        if not ln or ln.startswith('#'): continue
        a = [x.strip() for x in ln.split('|')]
        out.append(dict(ok=a[0], bad=a[1], typ=a[2], hz=a[3] if len(a) > 3 else '고유어'))
    return out

