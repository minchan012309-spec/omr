# 돼/되, 봬/뵈 등 문장 속 쓰임 (문장__, 옳은 것, 틀린 것, 설명)
def _sent(block):
    out = []
    for ln in block.strip().splitlines():
        ln = ln.strip()
        if not ln or ln.startswith('#'): continue
        a = [x.strip() for x in ln.split('|')]
        out.append(dict(s=a[0], ok=a[1], bad=[x.strip() for x in a[2].split('/')], why=a[3], art=a[4] if len(a) > 4 else ''))
    return out

