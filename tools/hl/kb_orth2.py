# 용언 활용 표: 어간 | 아/어형 | 으형 | 분류 | 규칙 활용일 때의 설명
def _irr(block):
    out = []
    for ln in block.strip().splitlines():
        ln = ln.strip()
        if not ln or ln.startswith('#'): continue
        a = [x.strip() for x in ln.split('|')]
        out.append(dict(verb=a[0], fa=a[1], fu=a[2], cat=a[3], note=a[4] if len(a) > 4 else ''))
    return out

