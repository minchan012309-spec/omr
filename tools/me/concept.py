def run(fig_src=None):
    old = json.load(open(os.path.join(ROOT, 'bank', 'concept.json'), encoding='utf-8'))
    data = json.loads(re.match(r'const DATA=(\[.*\]);?\s*$', open(os.path.join(ROOT, 'bank', 'data.js'), encoding='utf-8').read(), re.S).group(1))
    by_type = {}
    for q in data:
        if q.get('set') in ('ox', 'blank'): by_type.setdefault((q['set'], q.get('type')), []).append(q['code'])
    for s in SECS:
        s['ox'] = sorted({c for t in s['types'] for c in by_type.get(('ox', t), [])})
        s['blank'] = sorted({c for t in s['types'] for c in by_type.get(('blank', t), [])})
    summ = [dict(title=x['title'], html=AP.mathify(re.sub(r'<tr>(?:(?!</tr>).)*(상평형|연료)(?:(?!</tr>).)*</tr>', '', x['html']))) for x in old.get('summary', [])]
    pools = {}
    for k, v in old.get('pools', {}).items():
        if re.search('상평형|연료', k): continue
        pools[k] = [x for x in v if not re.search('상평형|연료|ln ?2', ' '.join(x))]
    out = dict(subs={k: dict(name=v[0], goal=re.sub(r'\\text\{([^}]*)\}', r'\1', v[1]).replace('$', '').replace('\\Delta ', 'Δ').replace('\\Delta', 'Δ').replace('_', '').replace('{', '').replace('}', '').replace("\\'", "'")) for k, v in SUBS.items()}, secs=SECS, summary=summ, pools=pools, pal=old.get('pal'), noDefaultBooks=old.get('noDefaultBooks', True),
               src='해원고 2026학년도 2학년 Ⅲ·Ⅳ단원 개념 학습지(빈칸 답 채움)')
    json.dump(out, open(os.path.join(ROOT, 'bank', 'concept.json'), 'w', encoding='utf-8'), ensure_ascii=False, separators=(',', ':'))
    if fig_src:
        from PIL import Image
        d = os.path.join(ROOT, 'fig', 'hw', 'c'); os.makedirs(d, exist_ok=True)
        for k, v in CF.items():
            im = Image.open(os.path.join(fig_src, 'figs2', v + '.png')).convert('L')
            if im.width > 1400: im = im.resize((1400, round(im.height * 1400 / im.width)), Image.LANCZOS)
            im.save(os.path.join(d, k + '.png'), optimize=True)
    print('개념 절', len(SECS), '/ OX·빈칸 연결', sum(len(s['ox']) + len(s['blank']) for s in SECS))

if __name__ == '__main__':
    run(os.environ.get('HW_FIG_SRC'))
