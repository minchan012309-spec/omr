# 쪽 전체에서 직접 잘라야 하는 그림(쪽 그림 경로, 비율 상자)
CROP = {'180': ('hi/3-2/p-1.png', (0.315, 0.686, 0.655, 0.775))}

def save(im, out):
    im = im.convert('L')
    if im.width > 1400: im = im.resize((1400, round(im.height * 1400 / im.width)), Image.LANCZOS)
    im.save(out, optimize=True)

def run(dst):
    os.makedirs(dst, exist_ok=True)
    for k, v in F.items():
        save(Image.open(os.path.join(SRC, 'figs2', v + '.png')), os.path.join(dst, k + '.png'))
    for k, (pg, b) in CROP.items():
        im = Image.open(os.path.join(SRC, pg)); W, H = im.size
        save(im.crop((int(b[0] * W), int(b[1] * H), int(b[2] * W), int(b[3] * H))), os.path.join(dst, k + '.png'))

if __name__ == '__main__':
    if not SRC: sys.exit('HW_FIG_SRC 를 잘라 둔 그림 폴더로 지정하세요')
    run(sys.argv[1] if len(sys.argv) > 1 else 'fig/hw')
