def fig_standing():
    f = Fig(320, 150)
    x0, x1, y = 30, 290, 70
    wl = (x1 - x0) / 1.5
    f.sin_path(x0, y, 40, wl, 1.5, c=BL, sw=2.4)
    f.sin_path(x0, y, -40, wl, 1.5, c=BL, sw=1.4)
    f.line(x0, 40, x0, 100, INK, 3)
    f.line(x1, 40, x1, 100, INK, 3)
    for k in range(4):
        f.circ(x0 + k * wl / 2, y, 3.2, INK, INK, 1)
    f.line(x0, 104, x0, 130, GR, 1, '4 3')
    f.line(x1, 104, x1, 130, GR, 1, '4 3')
    f.arrow(160, 124, x0, 124, INK, 1.3)
    f.arrow(160, 124, x1, 124, INK, 1.3)
    f.text(160, 144, 'L = 1.2 m', 13, bold=True)
    return FIG(f.svg(), '62%')


