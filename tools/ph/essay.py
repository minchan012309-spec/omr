def fig_incline():
    f = Fig(300, 190)
    f.poly([(40, 170), (240, 170), (240, 20)], '#eef2f8', INK, 1.6)
    f.hatch(30, 170, 220)
    s0, ln, hh = 70, 56, 36
    u, n = (0.8, -0.6), (-0.6, -0.8)
    p0 = (40 + u[0] * s0, 170 + u[1] * s0)
    p1 = (p0[0] + u[0] * ln, p0[1] + u[1] * ln)
    q1 = (p1[0] + n[0] * hh, p1[1] + n[1] * hh)
    q0 = (p0[0] + n[0] * hh, p0[1] + n[1] * hh)
    f.poly([p0, p1, q1, q0], '#fde8c8', INK, 1.6)
    cx = (p0[0] + p1[0] + q0[0] + q1[0]) / 4
    cy = (p0[1] + p1[1] + q0[1] + q1[1]) / 4
    f.text(cx, cy + 5, '5 kg', 13, bold=True, rot=-37)
    f.path('M82 170 A42 42 0 0 0 73.6 144.8', 'none', INK, 1.3)
    f.text(104, 163, '37°', 13)
    f.text(250, 100, '거친 빗면', 12.5, 'start', c=GR)
    return FIG(f.svg(), '58%')


