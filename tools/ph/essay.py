def fig_pv():
    p = Plot(320, 222, 4, 5, ml=56, mt=24, mb=38)
    p.axes('V (10⁻³ m³)', '', xticks=[0, 1, 2, 3], yticks=[0, 1, 2, 3, 4], grid=True)
    p.text(6, 14, 'P (10⁵ Pa)', 12.5, 'start', True, GR)
    A, B, C, D = (1, 4), (3, 4), (3, 2), (1, 2)
    pts = [A, B, C, D]
    p.poly([(p.px(x), p.py(y)) for x, y in pts], 'none', BL, 2.6)
    for i in range(4):
        (x1, y1), (x2, y2) = pts[i], pts[(i + 1) % 4]
        sx1, sy1, sx2, sy2 = p.px(x1), p.py(y1), p.px(x2), p.py(y2)
        mx, my = (sx1 + sx2) / 2, (sy1 + sy2) / 2
        d = math.hypot(sx2 - sx1, sy2 - sy1)
        ux, uy = (sx2 - sx1) / d, (sy2 - sy1) / d
        p._head(mx, my, mx + ux * 7, my + uy * 7, BL, 2.6)
    p.text(p.px(1) - 12, p.py(4) - 7, 'A', 14, bold=True)
    p.text(p.px(3) + 13, p.py(4) - 7, 'B', 14, bold=True)
    p.text(p.px(3) + 13, p.py(2) + 15, 'C', 14, bold=True)
    p.text(p.px(1) - 12, p.py(2) + 15, 'D', 14, bold=True)
    return FIG(p.svg(), '66%')


