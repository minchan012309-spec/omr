ESSAYS = []


def E(sub_key, label, pts, body, ans, steps, criteria, core, point):
    assert sub_key in SUB_ORDER, sub_key
    assert any(t['sub'] == sub_key and t['label'] == label for t in TYPES), (sub_key, label)
    assert 3 <= pts <= 5 and 2 <= len(criteria) <= 4 and 2 <= len(steps) <= 6
    assert all(c.startswith('①') or c[0] in '②③④' for c in criteria)
    ESSAYS.append(dict(sub=sub_key, type=label, pts=pts, body=body, ans=ans, steps=steps,
                       criteria=criteria, core=core, point=point))


