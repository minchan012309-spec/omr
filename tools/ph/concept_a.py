    H = 130
    data = [(0, 0, 20), (1, 15, 10), (2, 20, 0), (3, 15, -10), (4, 0, -20)]
    ys = lambda h: g - 7 - h / 20 * H
    f.path('M %s %s L %s %s' % (xa, ys(0), xa, ys(20)), stroke=GR, sw=1, dash='4 3')
    f.path('M %s %s L %s %s' % (xd, ys(0), xd, ys(20)), stroke=GR, sw=1, dash='4 3')
