def fig_kepler():
    f = Fig(340, 220)
    cx, cy, a, b = 170, 105, 135, 76
    c = math.sqrt(a * a - b * b)
    sx = cx + c
    P = lambda t: (cx + a * math.cos(t), cy - b * math.sin(t))
    f.ell(cx, cy, a, b, 'none', INK, 1.8)

    def area(t1, t2, n=200):
        pts = [(sx, cy)] + [P(t1 + (t2 - t1) * i / n) for i in range(n + 1)]
        s = 0
        for i in range(len(pts)):
            x1, y1 = pts[i]
            x2, y2 = pts[(i + 1) % len(pts)]
            s += x1 * y2 - x2 * y1
        return abs(s) / 2
    t1 = math.radians(40)
    A1 = area(-t1, t1)
    lo, hi = 0.01, 1.5
    for _ in range(60):
        m = (lo + hi) / 2
        if area(math.pi - m, math.pi + m) < A1: lo = m
        else: hi = m
    t2 = lo
    for (u, v, col) in ((-t1, t1, '#f9e3a1'), (math.pi - t2, math.pi + t2, '#cfe2f7')):
        pts = [(sx, cy)] + [P(u + (v - u) * i / 40) for i in range(41)]
        f.poly(pts, col, INK, 1.2)
    f.circ(sx, cy, 8, OR, INK, 1.4)
    f.text(sx - 24, cy + 32, '태양', 12, 'middle', True)
    f.circ(*P(0), 5, '#fff', INK, 1.6)
    f.circ(*P(math.pi), 5, '#fff', INK, 1.6)
    f.text(cx + a + 8, cy + 50, '근일점', 12, 'end', True, RD)
    f.text(cx - a - 2, cy + 26, '원일점', 12, 'start', True, BL)
    f.text(cx - 20, cy - 28, '같은 시간 동안 쓸고', 12, 'middle', False, GR)
